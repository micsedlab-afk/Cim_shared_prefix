def unique_tokens(tok,text,n):
    ids=tok.encode(text,add_special_tokens=False)
    if len(ids)<n:
        raise ValueError(f"written held-out passage too short ({len(ids)} tokens < {n})")
    return ids[:n]


def execute(args):
    import torch
    from transformers import AutoTokenizer,AutoModelForCausalLM
    torch.manual_seed(22848)
    torch.set_num_threads(args.threads)
    tokenizer=AutoTokenizer.from_pretrained(MODEL,revision=REVISION,trust_remote_code=False)
    model=AutoModelForCausalLM.from_pretrained(
        MODEL,revision=REVISION,torch_dtype=torch.float32,
        attn_implementation="eager",trust_remote_code=False).eval()
    L=model.config.num_hidden_layers
    P=args.prefix
    O=args.output
    ids=[torch.tensor([unique_tokens(tokenizer,x,P+O)],dtype=torch.long)
         for x in PASSAGES]
    with torch.no_grad():
        baseline=[nll_and_logits(model,s,P)[0] for s in ids]

    M=args.centroids
    scores=[]
    for lid in range(L):
        ms=[0]*L
        ms[lid]=M
        with replace_attention_prefix(model,P,ms,mode="q4k4"):
            loss,_=nll_and_logits(model,ids[0],P)
        scores.append(loss-baseline[0])
    # Calibration-derived rank; strictly no held-out passage influences it.
    rank=sorted(range(L),key=lambda l:(scores[l],l))
    sizes=tuple(sorted(set([0,1,2,4,6,8,12,16,24,L])))
    curves=[]
    selected=0
    for k in sizes:
        active=set(rank[:k])
        ms=[M if i in active else 0 for i in range(L)]
        with replace_attention_prefix(model,P,ms,mode="q4k4"):
            cal,_=nll_and_logits(model,ids[0],P)
        delta=cal-baseline[0]
        curves.append({
            "admitted_layers":k,
            "calibration_NLL":cal,
            "delta_calibration_NLL":delta,
            "satisfies_predeclared_budget":delta<=args.max_delta_nll,
        })
        if delta<=args.max_delta_nll:
            selected=k
    chosen=sorted(rank[:selected])
    M_by=[M if i in set(chosen) else 0 for i in range(L)]
    held=[]
    for i in (1,2):
        with replace_attention_prefix(model,P,M_by,mode="q4k4"):
            val,_=nll_and_logits(model,ids[i],P)
        held.append({
            "passage_index":i,
            "exact_reference_NLL":baseline[i],
            "candidate_NLL":val,
            "delta_NLL":val-baseline[i],
        })

    # A fixed-index control uses the same number of compressed layers but
    # no calibration. Only compare, never let it influence admission.
    first=[M if i<selected else 0 for i in range(L)]
    first_held=[]
    for i in (1,2):
        with replace_attention_prefix(model,P,first,mode="q4k4"):
            val,_=nll_and_logits(model,ids[i],P)
        first_held.append(val-baseline[i])

    geom=macro_summary_area(
        selected,model.config.num_key_value_heads,
        model.config.hidden_size//model.config.num_attention_heads,
        M,
    ) if selected else None

    result={
        "schema":"source-pretrained-smollm2-135m-calibrated-GPU-fallback/v1",
        "checkpoint":MODEL,"revision":REVISION,
        "pretrained_all_weights":True,"architecture":"Llama-like GQA 30 layers/9Q/3KV/64D",
        "precision":"FP32 base weights, ideal quantized signed Q4K4 prefix centroids; full exact GPU fallback",
        "P":P,"O":O,"centroids":M,
        "calibration_budget_delta_NLL":args.max_delta_nll,
        "calibration_reference_NLL":baseline[0],
        "heldout_reference_NLL":[baseline[1],baseline[2]],
        "single_layer_calibration_delta_NLL":scores,
        "calibration_ranked_layers":rank,
        "calibration_admission_curve":curves,
        "admitted_compressed_layers":chosen,
        "admitted_count":selected,
        "heldout":held,
        "heldout_mean_delta_NLL":float(np.mean([x["delta_NLL"] for x in held])),
        "first_layers_control_mean_delta_NLL":float(np.mean(first_held)),
        "selected_macro_storage":geom,
        "prompt_corpus":"three independently authored, nonrepeated domain passages (engineering, harbor, agriculture)",
        "next_token_targets_per_passage":O-1,
        "full_model_computation":"real pretrained GQA model; layer outputs causally propagated; exact suffix, prefill and non-admitted layers",
        "limitations":[
            "small checkpoint, only three authored passages, teacher-forced fixed context",
            "ideal signed Q4K4 math without hardware O4 ADC response",
            "calibration NLL budget cannot guarantee held-out task quality",
            "zero GPU/CIM latency or energy claims; benefits are memory-macro coverage potential"
        ],
    }
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(result,indent=2,sort_keys=True)+"\n")
    with args.csv.open("w",newline="") as fd:
        writer=csv.DictWriter(fd,fieldnames=["layer","isolated_calibration_delta_NLL","selected","calibration_rank"])
        writer.writeheader()
        for l in range(L):
            writer.writerow({"layer":l,"isolated_calibration_delta_NLL":scores[l],
                             "selected":l in set(chosen),"calibration_rank":rank.index(l)})
    print("PRETRAINED_SAFE_DISPATCH "+json.dumps(result,sort_keys=True),flush=True)


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--prefix",type=int,default=128)
    p.add_argument("--output",type=int,default=32)
    p.add_argument("--centroids",type=int,default=64)
    p.add_argument("--max-delta-nll",type=float,default=.1)
    p.add_argument("--threads",type=int,default=4)
    p.add_argument("--out",type=Path,required=True)
    p.add_argument("--csv",type=Path,required=True)
    execute(p.parse_args())
