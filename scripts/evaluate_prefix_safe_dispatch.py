"""Actual pretrained GQA selective-prefix admission with *exact* GPU fallback.

Use real checkpoint, true RoPE, full decoder propagation, pre-registered
calibration NLL budget, and two distinct held-out passages. The 30 one-layer
ablation experiments select a prefix-approximation subset; true causal
suffix and all other attention remain exactly computed on GPU.

No GPU/CIM timing or energy, no O4 ADC characterization, no 8B inference.
"""
